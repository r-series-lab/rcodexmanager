const localization = createLocalization<AppLanguage>({
  defaultLocale: "zh-CN",
  supportedLocales: ["zh-CN", "en-US"],
  catalogs: {
    "en-US": EN_US,
  },
  storageKey: LANGUAGE_STORAGE_KEY,
});

export const I18nProvider = localization.LocalizationProvider;
export const createTranslator = localization.createTranslator;

export function initialAppLanguage(): AppLanguage {
  return localization.readStoredLocale(
    typeof window === "undefined" ? undefined : window.localStorage,
  );
}

export function useI18n() {
  const { locale, t } = localization.useLocalization();
  return { language: locale, t };
}

export function persistAppLanguage(language: AppLanguage) {
  localization.writeStoredLocale(
    language,
    typeof window === "undefined" ? undefined : window.localStorage,
  );
}
